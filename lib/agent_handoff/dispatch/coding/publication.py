class PublicationError(RuntimeError):
    pass


class RemoteStateError(PublicationError):
    """A durable publication artifact is deterministically absent or invalid."""


def _slug(value: str, limit: int = 32) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", str(value or "").lower()).strip("-")
    return (text or "project")[:limit].strip("-") or "project"


def build_branch(prefix: str, project: str, issue_number: int, task_id: str) -> str:
    if not prefix_valid(prefix):
        raise PublicationError("the configured publication branch prefix is unsafe")
    branch = f"{prefix}{_slug(project)}/issue-{int(issue_number)}-{task_id}"
    try:
        return validate_branch_name(branch, "coding publication branch")
    except Exception as exc:
        raise PublicationError(sanitize_error(str(exc), 300)) from exc


def pr_marker(task_id: str, run_id: str) -> str:
    return PR_MARKER.format(task_id=task_id, run_id=run_id)


def build_pr_title(prefix: str | None, subject: str | None) -> str:
    """Join a configured prefix and an issue title with exactly one space.

    Older configurations may omit the trailing space after ``Agent Handoff:``.
    Normalizing here keeps existing configurations valid without rewriting
    stored config or renaming any existing pull request.
    """

    head = " ".join(str(prefix or "Agent Handoff:").split()) or "Agent Handoff:"
    text = " ".join(str(subject or "").split())
    if not text:
        return head
    return f"{head} {text}"


def build_commit_message(*, project: str, title: str, issue_number: int, task_id: str, run_id: str) -> str:
    subject = " ".join(str(title or "").split())[:120] or f"Agent Handoff issue #{issue_number}"
    return (
        f"Agent Handoff: {subject}\n\n"
        f"Project: {project}\n"
        f"Source issue: #{int(issue_number)}\n"
        f"Task: {task_id}\n"
        f"Run: {run_id}\n\n"
        "Generated by Agent Handoff C2. The publisher validates the task workspace,\n"
        "runs trusted tests, and never auto-merges.\n"
    )


def build_pr_body(
    *,
    task_id: str,
    run_id: str,
    title: str,
    issue_url: str | None,
    base_commit: str,
    branch: str,
    validation: Mapping[str, Any],
    tests: Mapping[str, Any],
    report_url: str | None = None,
    limitations: Sequence[str] = (),
) -> str:
    files = validation.get("files") or []
    file_lines = [
        f"- `{item.get('path')}` ({item.get('status')}, {item.get('size')} bytes)"
        for item in files[:80]
    ]
    if len(files) > 80:
        file_lines.append(f"- … and {len(files) - 80} more file(s)")
    test_lines = []
    for command in tests.get("commands") or []:
        argv = " ".join(str(part) for part in command.get("argv") or [])
        test_lines.append(
            f"- `{argv}` — `{command.get('status')}` exit `{command.get('exit_code')}` "
            f"({command.get('duration_seconds')}s)"
        )
    if not test_lines:
        test_lines.append("- No trusted test command was executed.")
    security_lines = [
        f"- Disposable workspace tied to `{base_commit}`; no developer checkout was modified.",
        f"- Trusted tests ran under the dedicated non-root identity; profile `{tests.get('profile')}`.",
        f"- Diff validation: `{validation.get('status')}`; changed files `{validation.get('changed_count')}`; "
        f"diff bytes `{validation.get('diff_bytes')}`.",
        f"- Protected path rules and secret scanning are defense in depth, not a complete proof of safety.",
    ]
    for reason in validation.get("blocked") or []:
        security_lines.append(f"- Blocked: {reason}")
    report_line = report_url or (
        "The verified Google Drive report link is published to the originating issue after "
        "MD5/read-back upload verification."
    )
    lines = [
        pr_marker(task_id, run_id),
        "## Agent Handoff task",
        "",
        f"**{title}**",
        "",
        f"- Source issue: {issue_url or 'not captured'}",
        f"- Base commit: `{base_commit}`",
        f"- Branch: `{branch}`",
        f"- Task: `{task_id}`",
        f"- Run: `{run_id}`",
        "- Publication: **Draft only**. No auto-merge, no direct push to the base branch.",
        "",
        "## Scope of changes",
        "",
        "The coding agent worked in a disposable clean workspace. Only the following validated files are included:",
        "",
        *file_lines,
        "",
        "## Test results",
        "",
        *test_lines,
        "",
        "## Security checks",
        "",
        *security_lines,
        "",
        "## Known limitations",
        "",
        *[f"- {item}" for item in limitations],
        "",
        "## Verified report",
        "",
        report_line,
        "",
        "This Pull Request is intentionally a Draft. A human owner must review and merge it.",
        "",
    ]
    return "\n".join(lines)


def _manifest_digest(manifest: Mapping[str, Any]) -> str:
    import hashlib

    canonical = json.dumps(manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()


def _validated_manifest(validation: Mapping[str, Any]) -> tuple[dict[str, dict[str, Any]], str]:
    if validation.get("status") != "passed":
        raise PublicationError("publication requires a passed diff validation result")
    manifest = validation.get("manifest")
    if not isinstance(manifest, dict) or manifest.get("schema") != 1 or not isinstance(manifest.get("files"), list):
        raise PublicationError("the validation manifest is missing or unsupported")
    recorded_digest = str(validation.get("manifest_sha256") or "")
    actual_digest = _manifest_digest(manifest)
    if not recorded_digest or recorded_digest != actual_digest:
        raise PublicationError("the validation manifest digest does not match its recorded digest")
    validation_paths = {
        safe_relative_path(str(item.get("path") or ""))
        for item in (validation.get("files") or [])
        if isinstance(item, dict)
    }
    entries: dict[str, dict[str, Any]] = {}
    for item in manifest["files"]:
        if not isinstance(item, dict):
            raise PublicationError("the validation manifest contains an invalid entry")
        path = safe_relative_path(str(item.get("path") or ""))
        if is_reserved_publication_path(path):
            raise PublicationError(f"the validation manifest targets a reserved publication name: {path}")
        if path in entries:
            raise PublicationError(f"the validation manifest contains a duplicate path: {path}")
        status = str(item.get("status") or "")
        if status not in ("added", "modified", "renamed", "copied", "deleted"):
            raise PublicationError(f"the validation manifest has an unsupported status for {path}")
        if status == "deleted":
            entries[path] = {"path": path, "status": status}
            continue
        digest = str(item.get("sha256") or "")
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise PublicationError(f"the validation manifest has no valid content digest for {path}")
        try:
            size = int(item.get("size"))
        except (TypeError, ValueError):
            raise PublicationError(f"the validation manifest has no valid size for {path}")
        mode = str(item.get("mode") or "")
        raw_mode = str(item.get("raw_mode") or "")
        if mode not in ("0644", "0755") or not re.fullmatch(r"[0-7]{4}", raw_mode):
            raise PublicationError(f"the validation manifest has no valid mode for {path}")
        entries[path] = {
            "path": path,
            "status": status,
            "sha256": digest,
            "size": size,
            "mode": mode,
            "raw_mode": raw_mode,
        }
    if set(entries) != validation_paths:
        raise PublicationError("the validation manifest paths do not match the reported changed files")
    if not entries:
        raise PublicationError("the validation manifest is empty")
    return entries, actual_digest


def _prepare_destination_directory(staging: str, relative: str) -> str:
    """Create missing parent directories without following symlinks."""

    safe = safe_relative_path(relative)
    current = os.path.realpath(staging)
    if not current:
        raise PublicationError("publication staging is unavailable")
    for part in safe.split("/")[:-1]:
        current = os.path.join(current, part)
        if os.path.lexists(current):
            info = os.lstat(current)
            if not stat.S_ISDIR(info.st_mode) or stat.S_ISLNK(info.st_mode):
                raise PublicationError(f"publication destination parent is not a safe directory: {relative}")
        else:
            os.mkdir(current, 0o700)
    destination = os.path.join(current, safe.split("/")[-1])
    if os.path.lexists(destination):
        info = os.lstat(destination)
        if stat.S_ISLNK(info.st_mode):
            raise PublicationError(f"publication destination is a symlink: {relative}")
        if not stat.S_ISREG(info.st_mode):
            raise PublicationError(f"publication destination is not a regular file: {relative}")
    return destination


def _copy_verified_file(
    source: str,
    destination: str,
    entry: Mapping[str, Any],
    *,
    max_bytes: int,
) -> None:
    try:
        size, data, raw_mode, digest = read_regular_file(source, max_bytes)
    except (OSError, ValueError) as exc:
        raise PublicationError(f"could not re-read validated artifact {entry['path']}: {sanitize_error(str(exc), 300)}") from exc
    if (
        size != int(entry["size"])
        or digest != entry["sha256"]
        or f"{raw_mode:04o}" != entry["raw_mode"]
        or normalized_publication_mode(raw_mode) != entry["mode"]
    ):
        raise PublicationError(
            f"artifact changed between validation and publication: {entry['path']} "
            "(content, size, or mode mismatch)"
        )
    parent = os.path.dirname(destination)
    if not os.path.isdir(parent) or os.path.islink(parent):
        raise PublicationError(f"publication destination parent is unsafe: {entry['path']}")
    flags_out = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    if hasattr(os, "O_NOFOLLOW"):
        flags_out |= os.O_NOFOLLOW
    output = os.open(destination, flags_out, 0o600)
    try:
        view = memoryview(data)
        written = 0
        while written < len(view):
            written += os.write(output, view[written:])
    finally:
        os.close(output)
    os.chmod(destination, int(entry["mode"], 8))
    try:
        dest_size, dest_data, dest_raw_mode, dest_digest = read_regular_file(destination, max_bytes)
    except (OSError, ValueError) as exc:
        raise PublicationError(f"could not verify copied artifact {entry['path']}") from exc
    if (
        dest_size != int(entry["size"])
        or dest_digest != entry["sha256"]
        or sha256_bytes(dest_data) != entry["sha256"]
        or normalized_publication_mode(dest_raw_mode) != entry["mode"]
    ):
        raise PublicationError(f"copied artifact verification failed: {entry['path']}")


def _git_bytes(git: SafeGit, cwd: str, spec: str) -> bytes:
    result = git.run(["cat-file", "-p", spec], cwd=cwd, text=False)
    data = result.stdout if isinstance(result.stdout, bytes) else bytes(result.stdout or b"")
    return data


def _verify_index_entry(git: SafeGit, staging: str, entry: Mapping[str, Any]) -> None:
    result = git.run(["ls-files", "-s", "-z", "--", entry["path"]], cwd=staging, check=False)
    if entry["status"] == "deleted":
        if result.returncode == 0 and (result.stdout or "").strip("\x00"):
            raise PublicationError(f"a deleted path is still present in the publication index: {entry['path']}")
        return
    fields = [item for item in (result.stdout or "").split("\x00") if item]
    if len(fields) != 1:
        raise PublicationError(f"the publication index does not contain exactly one entry for {entry['path']}")
    metadata, _path = fields[0].split("\t", 1)
    mode, _oid, _stage = metadata.split(" ", 2)
    expected_mode = "100755" if entry["mode"] == "0755" else "100644"
    if mode != expected_mode:
        raise PublicationError(f"the publication index mode does not match the manifest for {entry['path']}")
    data = _git_bytes(git, staging, f":{entry['path']}")
    if len(data) != int(entry["size"]) or sha256_bytes(data) != entry["sha256"]:
        raise PublicationError(f"the publication index content does not match the manifest for {entry['path']}")


def _verify_committed_entry(git: SafeGit, staging: str, entry: Mapping[str, Any]) -> None:
    tree = git.run(["ls-tree", "-z", "HEAD", "--", entry["path"]], cwd=staging, check=False)
    fields = [item for item in (tree.stdout or "").split("\x00") if item]
    if entry["status"] == "deleted":
        if fields:
            raise PublicationError(f"a deleted path is still present in the committed tree: {entry['path']}")
        return
    if len(fields) != 1:
        raise PublicationError(f"the committed tree does not contain exactly one entry for {entry['path']}")
    metadata, _path = fields[0].split("\t", 1)
    mode, kind, _oid = metadata.split(" ", 2)
    expected_mode = "100755" if entry["mode"] == "0755" else "100644"
    if kind != "blob" or mode != expected_mode:
        raise PublicationError(f"the committed tree mode/type does not match the manifest for {entry['path']}")
    data = _git_bytes(git, staging, f"HEAD:{entry['path']}")
    if len(data) != int(entry["size"]) or sha256_bytes(data) != entry["sha256"]:
        raise PublicationError(f"the committed tree content does not match the manifest for {entry['path']}")


class TrustedPublisher:
    """Create one commit in a parent-owned staging repo and publish one Draft PR.

    The coding child never receives parent Git or GitHub credentials. The
    publisher reads only validated regular files from the task workspace and
    never runs repository hooks or repository-controlled filters with parent
    privileges.
    """

    def __init__(
        self,
        *,
        repository: str,
        base_branch: str,
        branch_prefix: str,
        staging_root: str,
        gh_command: str = "gh",
        token_env: str | None = None,
        timeout: float = 120.0,
        token_provider: Callable[[], str] | None = None,
        git: SafeGit | None = None,
        max_file_bytes: int = 200_000,
        remote_url: str | None = None,
    ) -> None:
        self.repository = repository
        self.base_branch = base_branch
        self.branch_prefix = branch_prefix
        self.staging_root = staging_root
        self.gh_command = gh_command
        self.token_env = token_env
        self.timeout = timeout
        self._token_provider = token_provider
        self.git = git or SafeGit(identity=None, timeout=timeout)
        self.max_file_bytes = max_file_bytes
        self._remote_url = remote_url or f"https://github.com/{repository}.git"
        self._owner = repository.split("/", 1)[0]
        self._staging: str | None = None

    @staticmethod
    def _redact_token(text: Any, token: str) -> str:
        value = sanitize_error(str(text or ""), 1000)
        return value.replace(token, "[REDACTED]") if token else value

    def token(self) -> str:
        if self._token_provider is not None:
            value = self._token_provider() or ""
        elif self.token_env:
            value = os.environ.get(self.token_env) or ""
        else:
            result = run_command([self.gh_command, "auth", "token"], timeout=30)
            value = (result.stdout or "").strip() if result.returncode == 0 else ""
        if not value or "\n" in value or "\r" in value:
            raise PublicationError(
                "trusted GitHub publication credentials are unavailable; configure git/gh authentication "
                "or dispatch.coding.publication.token_env. The coding child never receives this credential."
            )
        return value

    @staticmethod
    def _remove_auth_directory(auth_dir: str, root: str) -> None:
        """Remove one parent-created auth directory and never follow a swap."""

        try:
            target = os.path.realpath(auth_dir)
        except OSError:
            return
        root_real = os.path.realpath(root)
        if target == root_real or not target.startswith(root_real.rstrip("/") + "/"):
            return
        if not os.path.basename(target).startswith(INTERNAL_AUTH_PREFIX):
            return
        try:
            info = os.lstat(target)
        except OSError:
            return
        if not stat.S_ISDIR(info.st_mode) or info.st_uid not in {0, os.geteuid()}:
            return
        shutil.rmtree(target, ignore_errors=True)

    @contextmanager
    def _auth_environment(self, token: str) -> Iterator[dict[str, str]]:
        """Create a short-lived parent-owned Git askpass helper.

        The helper directory is never the publication staging directory and is
        never reused. It is created exclusively, verified, and removed after
        every Git authentication operation, including failures.
        """

        root = self.validate_staging_root()
        auth_dir = tempfile.mkdtemp(prefix=INTERNAL_AUTH_PREFIX, dir=root)
        script_path = os.path.join(auth_dir, ".askpass.sh")
        try:
            info = os.lstat(auth_dir)
            if (
                not stat.S_ISDIR(info.st_mode)
                or stat.S_ISLNK(info.st_mode)
                or info.st_uid not in {0, os.geteuid()}
                or info.st_mode & 0o077
            ):
                raise PublicationError("the private Git authentication directory is not trusted")
            flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
            if hasattr(os, "O_NOFOLLOW"):
                flags |= os.O_NOFOLLOW
            descriptor = os.open(script_path, flags, 0o700)
            try:
                os.fchmod(descriptor, 0o700)
                payload = ASKPASS_SCRIPT.encode("utf-8")
                written = 0
                while written < len(payload):
                    written += os.write(descriptor, payload[written:])
                os.fsync(descriptor)
                script_stat = os.fstat(descriptor)
                if not stat.S_ISREG(script_stat.st_mode) or script_stat.st_uid not in {0, os.geteuid()}:
                    raise PublicationError("the Git authentication helper is not a trusted regular file")
            finally:
                os.close(descriptor)
            helper_stat = os.lstat(script_path)
            if stat.S_ISLNK(helper_stat.st_mode) or not stat.S_ISREG(helper_stat.st_mode):
                raise PublicationError("the Git authentication helper was replaced by a symlink or special file")
            read_flags = os.O_RDONLY
            if hasattr(os, "O_NOFOLLOW"):
                read_flags |= os.O_NOFOLLOW
            reader = os.open(script_path, read_flags)
            try:
                helper_data = os.read(reader, len(ASKPASS_SCRIPT.encode("utf-8")) + 1)
            finally:
                os.close(reader)
            if helper_data != ASKPASS_SCRIPT.encode("utf-8"):
                raise PublicationError("the Git authentication helper content is not trusted")
            if stat.S_IMODE(helper_stat.st_mode) != 0o700:
                raise PublicationError("the Git authentication helper mode is not private")
            yield {
                "GIT_ASKPASS": script_path,
                "GIT_ASKPASS_REQUIRE": "force",
                "GIT_TERMINAL_PROMPT": "0",
                "AH_PUBLISH_TOKEN": token,
            }
        finally:
            self._remove_auth_directory(auth_dir, root)

    def _gh(self, args: list[str], token: str, *, timeout: float | None = None) -> str:
        result = run_command(
            [self.gh_command, *args],
            timeout=timeout or self.timeout,
            env={"GH_TOKEN": token, "GITHUB_TOKEN": token, "GH_PROMPT_DISABLED": "1"},
        )
        if result.returncode != 0:
            detail = self._redact_token(
                result.stderr or result.stdout or f"gh exited {result.returncode}", token
            )
            raise PublicationError(detail)
        return result.stdout

    def validate_staging_root(self) -> str:
        if not self.staging_root:
            raise PublicationError("dispatch.coding.staging_root is not configured")
        root = os.path.realpath(self.staging_root)
        if not os.path.isdir(root):
            raise PublicationError("the publication staging root does not exist")
        entry = os.stat(root)
        if entry.st_uid not in {0, os.geteuid()}:
            raise PublicationError("the publication staging root must be owned by the dispatcher identity")
        if entry.st_mode & 0o077:
            raise PublicationError("the publication staging root must not be accessible by group/other")
        try:
            from ..security import _check_trusted_ancestors

            _check_trusted_ancestors(root, {"uid": os.geteuid(), "gid": os.getegid()}, "publication staging root")
        except Exception as exc:
            raise PublicationError(f"the publication staging root has unsafe ancestors: {exc}") from exc
        return root

    def _prepare_staging(self, task_id: str, run_id: str) -> str:
        root = self.validate_staging_root()
        name = f"{task_id}-{run_id}"
        if not STAGING_NAME_RE.fullmatch(name):
            raise PublicationError("the publication staging name is unsafe")
        staging = os.path.join(root, name)
        if os.path.lexists(staging):
            if os.path.islink(staging) or not os.path.isdir(staging):
                raise PublicationError("publication staging is not a safe directory")
            existing = os.lstat(staging)
            if existing.st_uid not in {0, os.geteuid()} or existing.st_mode & 0o022:
                raise PublicationError("publication staging ownership/mode is not trusted for replacement")
            shutil.rmtree(staging)
        os.mkdir(staging, 0o700)
        self._staging = os.path.realpath(staging)
        if not self._staging.startswith(root.rstrip("/") + "/"):
            raise PublicationError("publication staging escaped the managed root")
        return self._staging

    def adopt_staging(self, path: str) -> str:
        root = self.validate_staging_root()
        try:
            entry = os.lstat(path)
        except OSError as exc:
            raise PublicationError("the persisted publication staging directory is missing") from exc
        if stat.S_ISLNK(entry.st_mode) or not stat.S_ISDIR(entry.st_mode):
            raise PublicationError("the persisted publication staging must be a real directory, not a symlink")
        if entry.st_uid not in {0, os.geteuid()} or entry.st_mode & 0o022:
            raise PublicationError("the persisted publication staging ownership/mode is not trusted")
        target = os.path.realpath(path)
        if target == root or not target.startswith(root.rstrip("/") + "/"):
            raise PublicationError("the persisted publication staging path escaped the managed root")
        if not STAGING_NAME_RE.fullmatch(os.path.basename(target)):
            raise PublicationError("the persisted publication staging name is unsafe")
        git_entry = os.path.join(target, ".git")
        try:
            git_stat = os.lstat(git_entry)
        except OSError as exc:
            raise PublicationError("the persisted publication staging has no Git metadata") from exc
        if (
            stat.S_ISLNK(git_stat.st_mode)
            or not stat.S_ISDIR(git_stat.st_mode)
            or git_stat.st_uid not in {0, os.geteuid()}
            or git_stat.st_mode & 0o022
        ):
            raise PublicationError("the persisted publication staging Git metadata is not trusted")
        self._staging = target
        return target

    def verify_repository(self) -> dict[str, Any]:
        token = self.token()
        text = self._gh(["api", f"repos/{self.repository}"], token)
        try:
            data = json.loads(text)
        except ValueError as exc:
            raise PublicationError("GitHub returned invalid repository metadata") from exc
        if not isinstance(data, dict):
            raise PublicationError("GitHub repository metadata is not an object")
        full_name = str(data.get("full_name") or "")
        if full_name.lower() != self.repository.lower():
            raise PublicationError("the configured coding repository does not match GitHub")
        return {"repository": full_name, "private": bool(data.get("private"))}

    def prepare(self, *, base_commit: str, task_id: str, run_id: str) -> str:
        """Fetch the trusted base from GitHub into a fresh parent-owned repository."""

        token = self.token()
        self.verify_repository()
        staging = self._prepare_staging(task_id, run_id)
        with self._auth_environment(token) as auth:
            self.git.run(["init", "--quiet"], cwd=staging, env=auth)
            self.git.run(["remote", "add", "origin", self._remote_url], cwd=staging)
            self.git.run(
                ["fetch", "--no-tags", "--quiet", "origin", self.base_branch],
                cwd=staging,
                timeout=max(120.0, self.timeout),
                env=auth,
            )
            exists = self.git.run(
                ["cat-file", "-e", f"{base_commit}^{{commit}}"], cwd=staging, check=False
            )
            if exists.returncode != 0:
                raise PublicationError("the verified base commit is not available from the trusted repository")
            ancestor = self.git.run(
                ["merge-base", "--is-ancestor", base_commit, "FETCH_HEAD"], cwd=staging, check=False
            )
            if ancestor.returncode != 0:
                raise PublicationError("the verified base commit is not an ancestor of the trusted base branch")
            self.git.run(["checkout", "--detach", "--quiet", base_commit, "--"], cwd=staging, env=auth)
        return staging

    def stage_and_commit(
        self,
        *,
        validation: Mapping[str, Any],
        task_workspace: str,
        project: str,
        title: str,
        issue_number: int,
        task_id: str,
        run_id: str,
        base_commit: str,
    ) -> dict[str, str]:
        staging = self._staging
        if not staging:
            raise PublicationError("publication staging is not initialized")
        manifest_entries, manifest_digest = _validated_manifest(validation)
        expected: set[str] = set(manifest_entries)
        for path, entry in manifest_entries.items():
            if is_reserved_publication_path(path):
                raise PublicationError(f"the validation manifest targets a reserved publication name: {path}")
            if entry["status"] == "deleted":
                result = self.git.run(
                    ["rm", "--ignore-unmatch", "-f", "--", path], cwd=staging, check=False
                )
                if result.returncode != 0:
                    raise PublicationError(f"could not stage a validated deletion: {path}")
                continue
            source = workspace_entry_path(task_workspace, path)
            destination = _prepare_destination_directory(staging, path)
            _copy_verified_file(
                source,
                destination,
                entry,
                max_bytes=self.max_file_bytes,
            )
            self.git.run(["add", "-f", "--", path], cwd=staging)
        staged = self.git.run(
            ["diff", "--cached", "--name-only", "--no-renames", "-z"], cwd=staging
        )
        staged_paths = {item for item in (staged.stdout or "").split("\x00") if item}
        if staged_paths != expected:
            unexpected = sorted(staged_paths - expected)
            missing = sorted(expected - staged_paths)
            raise PublicationError(
                "staged publication paths do not match the validated manifest "
                f"(unexpected={unexpected[:5]}, missing={missing[:5]})"
            )
        for path, entry in manifest_entries.items():
            _verify_index_entry(self.git, staging, entry)
        message = build_commit_message(
            project=project,
            title=title,
            issue_number=issue_number,
            task_id=task_id,
            run_id=run_id,
        )
        self.git.run(
            [
                "-c",
                "user.name=Agent Handoff",
                "-c",
                "user.email=agent-handoff@localhost",
                "commit",
                "--no-verify",
                "--quiet",
                "-m",
                message,
            ],
            cwd=staging,
        )
        sha = (self.git.run(["rev-parse", "HEAD"], cwd=staging).stdout or "").strip()
        if not re.fullmatch(r"[0-9a-f]{40,64}", sha):
            raise PublicationError("the publication commit SHA could not be verified")
        parent = (self.git.run(["rev-parse", "HEAD^"], cwd=staging).stdout or "").strip()
        if parent != base_commit:
            raise PublicationError("the publication commit is not based on the verified base commit")
        changed = self.git.run(
            ["diff-tree", "--no-commit-id", "--name-only", "--no-renames", "-r", "-z", "HEAD"], cwd=staging
        )
        committed_paths = {item for item in (changed.stdout or "").split("\x00") if item}
        if committed_paths != expected:
            raise PublicationError("the commit contains paths outside the validated manifest")
        for path, entry in manifest_entries.items():
            _verify_committed_entry(self.git, staging, entry)
        return {
            "commit": sha,
            "staging": staging,
            "message": message,
            "manifest_sha256": manifest_digest,
        }

    def _remote_branch_sha(self, branch: str, token: str) -> str | None:
        cwd = self._staging if self._staging and os.path.isdir(self._staging) else self.validate_staging_root()
        with self._auth_environment(token) as auth:
            result = self.git.run(
                ["ls-remote", "--heads", self._remote_url, f"refs/heads/{branch}"],
                cwd=cwd,
                env=auth,
                check=False,
                timeout=self.timeout,
            )
        if result.returncode != 0:
            detail = self._redact_token(
                (result.stderr.decode("utf-8", errors="replace") if isinstance(result.stderr, bytes) else result.stderr)
                or (result.stdout.decode("utf-8", errors="replace") if isinstance(result.stdout, bytes) else result.stdout)
                or "git ls-remote failed",
                token,
            )
            raise PublicationError(f"could not verify the remote branch state: {detail}")
        for line in (result.stdout or "").splitlines():
            parts = line.split()
            if len(parts) == 2 and parts[1].endswith(f"refs/heads/{branch}"):
                return parts[0]
        return None

    def remote_branch_sha(self, branch: str) -> str | None:
        if not prefix_valid(self.branch_prefix) or not branch.startswith(self.branch_prefix):
            raise PublicationError("the publication branch is outside the trusted branch namespace")
        if branch.lower() in PROTECTED_BRANCHES:
            raise PublicationError("direct publication to a protected branch is refused")
        return self._remote_branch_sha(branch, self.token())

    def push(self, *, branch: str, commit: str) -> dict[str, Any]:
        if not self._staging:
            raise PublicationError("publication staging is not initialized")
        if not prefix_valid(self.branch_prefix) or not branch.startswith(self.branch_prefix):
            raise PublicationError("the publication branch is outside the trusted branch namespace")
        if branch.lower() in PROTECTED_BRANCHES or branch in (self.base_branch, f"refs/heads/{self.base_branch}"):
            raise PublicationError("direct publication to the protected base branch is refused")
        token = self.token()
        existing = self._remote_branch_sha(branch, token)
        if existing:
            if existing == commit:
                return {"branch": branch, "commit": commit, "pushed": True, "reused": True}
            raise PublicationError(
                "the publication branch already exists with a different commit; refusing to force-push "
                "or replace a previously published result"
            )
        with self._auth_environment(token) as auth:
            result = self.git.run(
                ["push", "--porcelain", "origin", f"{commit}:refs/heads/{branch}"],
                cwd=self._staging,
                env=auth,
                check=False,
                timeout=max(120.0, self.timeout),
            )
        if result.returncode != 0:
            recovered = self._remote_branch_sha(branch, token)
            if recovered == commit:
                return {"branch": branch, "commit": commit, "pushed": True, "recovered": True}
            detail = self._redact_token(result.stderr or result.stdout or "git push failed", token)
            raise PublicationError(f"publishing the task branch failed: {detail}")
        verified = self._remote_branch_sha(branch, token)
        if verified != commit:
            raise PublicationError("the pushed branch SHA could not be verified on the trusted repository")
        return {"branch": branch, "commit": commit, "pushed": True, "recovered": False}

    def _list_pulls(self, branch: str, token: str) -> list[dict[str, Any]]:
        query = quote(f"{self._owner}:{branch}", safe="")
        text = self._gh(
            ["api", f"repos/{self.repository}/pulls?state=all&head={query}&per_page=100"],
            token,
        )
        try:
            data = json.loads(text)
        except ValueError as exc:
            raise PublicationError("GitHub returned invalid PR metadata") from exc
        if isinstance(data, dict):
            data = [data]
        if not isinstance(data, list):
            raise PublicationError("GitHub PR metadata is not a list")
        return [item for item in data if isinstance(item, dict)]

    @staticmethod
    def _pr_matches(item: Mapping[str, Any], branch: str, repository: str, commit: str, marker: str) -> bool:
        head = item.get("head") or {}
        repo = (head.get("repo") or {}).get("full_name") or ""
        if str(head.get("ref") or "") != branch:
            return False
        if repo and str(repo).lower() != repository.lower():
            return False
        if str(item.get("body") or "").find(marker) >= 0:
            return True
        return str(head.get("sha") or "") == commit

    def _validate_pr(
        self,
        item: Mapping[str, Any],
        branch: str,
        commit: str | None = None,
    ) -> dict[str, Any]:
        head = item.get("head") or {}
        base = item.get("base") or {}
        if str(item.get("state") or "open") != "open":
            raise PublicationError("GitHub returned a closed or merged Pull Request; refusing to reuse it")
        if str(head.get("ref") or "") != branch:
            raise PublicationError("GitHub returned a Pull Request with an unexpected head branch")
        if str(base.get("ref") or self.base_branch) != self.base_branch:
            raise PublicationError("GitHub returned a Pull Request with an unexpected base branch")
        if item.get("draft") is not True:
            raise PublicationError("C2 refuses to publish or reuse a non-Draft Pull Request")
        head_sha = str(head.get("sha") or "")
        if commit and re.fullmatch(r"[0-9a-f]{40,64}", head_sha):
            if head_sha.strip("0") and head_sha != commit:
                raise PublicationError(
                    "the existing Pull Request head SHA does not match the verified publication commit"
                )
        if not item.get("html_url") or not isinstance(item.get("number"), int):
            raise PublicationError("GitHub returned incomplete Pull Request metadata")
        return item

    def get_pr(self, pr_number: int) -> dict[str, Any]:
        token = self.token()
        text = self._gh(["api", f"repos/{self.repository}/pulls/{int(pr_number)}"], token)
        try:
            item = json.loads(text)
        except ValueError as exc:
            raise PublicationError("GitHub returned invalid Pull Request metadata") from exc
        if not isinstance(item, dict) or int(item.get("number", -1)) != int(pr_number):
            raise PublicationError("GitHub returned incomplete Pull Request metadata")
        return item

    @staticmethod
    def body_sha256(body: Any) -> str:
        return hashlib.sha256(str(body or "").encode("utf-8")).hexdigest()

    @staticmethod
    def _is_not_found(error: BaseException) -> bool:
        text = str(error).lower()
        return "not found" in text or "http 404" in text or "404" in text or "gone" in text

    @staticmethod
    def pr_number_from_url(url: str | None) -> int | None:
        match = re.search(r"/pull/([0-9]+)(?:$|[/?#])", str(url or ""))
        return int(match.group(1)) if match else None

    def verify_published_state(
        self,
        *,
        branch: str,
        commit: str,
        pr_number: int | None = None,
        pr_url: str | None = None,
    ) -> dict[str, Any]:
        """Verify the live remote branch and Draft PR against durable evidence.

        Deterministic remote invalidation raises ``RemoteStateError``. Transient
        GitHub/Git failures raise ``PublicationError`` so callers can retry
        without misclassifying them as corruption.
        """

        if not prefix_valid(self.branch_prefix) or not branch.startswith(self.branch_prefix):
            raise RemoteStateError("the recorded publication branch is outside the trusted namespace")
        if branch.lower() in PROTECTED_BRANCHES:
            raise RemoteStateError("the recorded publication branch is a protected branch")
        token = self.token()
        remote_sha = self._remote_branch_sha(branch, token)
        if remote_sha is None:
            raise RemoteStateError(
                f"the published remote branch {branch!r} no longer exists"
            )
        if remote_sha != commit:
            raise RemoteStateError(
                f"the published remote branch {branch!r} moved from the verified commit "
                f"{commit} to {remote_sha}"
            )
        if pr_number is None and pr_url:
            pr_number = self.pr_number_from_url(pr_url)
        if pr_number is None:
            return {"branch_sha": remote_sha, "pr": None}
        try:
            item = self.get_pr(int(pr_number))
        except PublicationError as exc:
            if self._is_not_found(exc):
                raise RemoteStateError(
                    f"the recorded Draft Pull Request #{int(pr_number)} no longer exists"
                ) from exc
            raise
        head = item.get("head") or {}
        base = item.get("base") or {}
        head_repo = str((head.get("repo") or {}).get("full_name") or "")
        if head_repo.lower() != self.repository.lower():
            raise RemoteStateError("the Pull Request head repository no longer matches the configured repository")
        base_repo = str((base.get("repo") or {}).get("full_name") or "")
        if base_repo and base_repo.lower() != self.repository.lower():
            raise RemoteStateError("the Pull Request base repository no longer matches the configured repository")
        if str(item.get("state") or "") != "open":
            raise RemoteStateError(
                f"the recorded Draft Pull Request #{int(pr_number)} is no longer open "
                f"(state={item.get('state') or 'unknown'})"
            )
        if item.get("draft") is not True:
            raise RemoteStateError("the recorded Draft Pull Request was converted to Ready for review")
        if str(head.get("ref") or "") != branch:
            raise RemoteStateError("the Pull Request head branch no longer matches the recorded branch")
        if str(base.get("ref") or self.base_branch) != self.base_branch:
            raise RemoteStateError("the Pull Request base branch no longer matches the configured base branch")
        head_sha = str(head.get("sha") or "")
        if re.fullmatch(r"[0-9a-f]{40,64}", head_sha) and head_sha.strip("0") and head_sha != commit:
            raise RemoteStateError(
                "the Pull Request head SHA no longer matches the verified publication commit"
            )
        if not item.get("html_url") or not isinstance(item.get("number"), int):
            raise RemoteStateError("GitHub returned incomplete Pull Request metadata")
        return {"branch_sha": remote_sha, "pr": item}

    def create_or_reuse_pr(
        self,
        *,
        branch: str,
        commit: str,
        task_id: str,
        run_id: str,
        title: str,
        body: str,
    ) -> dict[str, Any]:
        token = self.token()
        marker = pr_marker(task_id, run_id)
        existing = [
            item
            for item in self._list_pulls(branch, token)
            if self._pr_matches(item, branch, self.repository, commit, marker)
        ]
        if len(existing) > 1:
            raise PublicationError("multiple Pull Requests already use this task branch; refusing to guess")
        if existing:
            item = self._validate_pr(existing[0], branch, commit)
            return {
                "pr_number": item.get("number"),
                "pr_url": item.get("html_url"),
                "created": False,
                "draft": True,
                "body_sha256": hashlib.sha256(str(item.get("body") or "").encode("utf-8")).hexdigest(),
            }
        args = [
            "api",
            f"repos/{self.repository}/pulls",
            "-X",
            "POST",
            "-f",
            f"title={title}",
            "-f",
            f"head={branch}",
            "-f",
            f"base={self.base_branch}",
            "-f",
            f"body={body}",
            "-F",
            "draft=true",
        ]
        try:
            text = self._gh(args, token)
            item = json.loads(text)
            if not isinstance(item, dict):
                raise PublicationError("GitHub returned invalid PR creation metadata")
            item = self._validate_pr(item, branch, commit)
            return {
                "pr_number": item.get("number"),
                "pr_url": item.get("html_url"),
                "created": True,
                "draft": True,
                "body_sha256": hashlib.sha256(str(item.get("body") or "").encode("utf-8")).hexdigest(),
            }
        except (PublicationError, ValueError) as exc:
            recovered = [
                item
                for item in self._list_pulls(branch, token)
                if self._pr_matches(item, branch, self.repository, commit, marker)
            ]
            if len(recovered) == 1:
                item = self._validate_pr(recovered[0], branch, commit)
                return {
                    "pr_number": item.get("number"),
                    "pr_url": item.get("html_url"),
                    "created": False,
                    "recovered": True,
                    "draft": True,
                    "body_sha256": hashlib.sha256(str(item.get("body") or "").encode("utf-8")).hexdigest(),
                }
            if len(recovered) > 1:
                raise PublicationError("PR recovery found multiple matching Pull Requests") from exc
            raise PublicationError(
                sanitize_error(f"creating the Draft Pull Request failed: {exc}", 800)
            ) from exc

    def update_pr_body(
        self,
        *,
        pr_number: int,
        body: str,
        branch: str | None = None,
        commit: str | None = None,
        expected_body_sha256: str | None = None,
    ) -> dict[str, Any]:
        token = self.token()
        if branch:
            existing = self.get_pr(int(pr_number))
            self._validate_pr(existing, branch, commit)
            if expected_body_sha256 and self.body_sha256(existing.get("body")) != expected_body_sha256:
                raise PublicationError(
                    "the Draft PR body changed before the update; refusing to overwrite external edits"
                )
        result = self._gh(
            [
                "api",
                f"repos/{self.repository}/pulls/{int(pr_number)}",
                "-X",
                "PATCH",
                "-f",
                f"body={body}",
            ],
            token,
        )
        try:
            item = json.loads(result)
        except ValueError as exc:
            raise PublicationError("GitHub returned invalid PR update metadata") from exc
        if not isinstance(item, dict) or int(item.get("number", -1)) != int(pr_number):
            raise PublicationError("GitHub did not confirm the Pull Request body update")
        return {"pr_number": pr_number, "pr_url": item.get("html_url") or None, "updated": True}

    def cleanup_persisted(self, path: str, *, expected_name: str | None = None) -> bool:
        """Best-effort cleanup of a persisted staging path after interruption."""

        if not path:
            return True
        try:
            root = self.validate_staging_root()
        except PublicationError:
            return False
        try:
            entry = os.lstat(path)
        except OSError:
            return True
        if stat.S_ISLNK(entry.st_mode) or not stat.S_ISDIR(entry.st_mode):
            return False
        if entry.st_uid not in {0, os.geteuid()} or entry.st_mode & 0o022:
            return False
        target = os.path.realpath(path)
        if target == root or not target.startswith(root.rstrip("/") + "/"):
            return False
        if not STAGING_NAME_RE.fullmatch(os.path.basename(target)):
            return False
        if expected_name and os.path.basename(target) != expected_name:
            return False
        shutil.rmtree(target, ignore_errors=True)
        return not os.path.lexists(target)

    def cleanup(self, *, preserve: bool = False) -> bool:
        staging = self._staging
        if not staging:
            return True
        if preserve:
            return True
        root = os.path.realpath(self.staging_root)
        target = os.path.realpath(staging)
        if target == root or not target.startswith(root.rstrip("/") + "/"):
            return False
        if not STAGING_NAME_RE.fullmatch(os.path.basename(target)):
            return False
        try:
            entry = os.lstat(target)
        except OSError:
            return True
        if entry.st_uid not in {0, os.geteuid()} or entry.st_mode & 0o022:
            return False
        shutil.rmtree(target, ignore_errors=True)
        return not os.path.lexists(target)
